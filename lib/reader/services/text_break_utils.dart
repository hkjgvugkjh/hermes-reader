/// CJK 排版中不可做行首的字符（右引号/右括号）。
///
/// 仅用于分页切割：页边界若紧跟这些字符（如 `…什么吧？”` 的 `”`），
/// 则将其吸收进当前页，避免下一页以 `”` 开头（页首引号孤行）。
///
/// 注意：不要用 U+2060 Word Joiner 在行内禁止断行——实测华为设备字体回退中
/// U+2060 具有非零宽度，会在引号密集页累计膨胀 1~2 行，导致分页测量与渲染
/// 不一致而溢出。
const kLineStartForbidden = {
  '”', '’', '」', '』', '）', '"', '\'',
  '＂', '＇', // 全角变体
};

/// 把 [text] 中「视觉行首」的全角空格 U+3000 替换为 U+3164（HANGUL FILLER）。
///
/// 为什么需要：SkParagraph 在 `TextAlign.justify` 且文本发生换行时，会把
/// **每行行首的空白**（包括中文段首缩进的 U+3000，乃至 NBSP/EM SPACE 等
/// 一切 `White_Space=Yes` 字符）折叠成零宽——段首缩进因此完全消失。
/// `TextAlign.left` 不折叠，但阅读器需要两端对齐。
///
/// U+3164 的特性恰好适合做占位：`White_Space=No`（不参与行首折叠）、
/// 字形为空（不可见）、CJK 字体中宽度为一个全角（1em）。替换是 **1:1 等长**
/// 的，因此替换前后的字符串共享同一偏移系——分页 offset、划选换算都无需
/// 任何映射。
///
/// 只替换「行首」（文本开头或 \n 之后）连续 U+3000；行中用作词间空格的
/// U+3000 不受影响。函数幂等（U+3164 不再被匹配）。
String uncollapseLeadingIndents(String text) {
  if (!text.contains('\u3000')) return text;
  return text.replaceAllMapped(RegExp('(^|\n)(\u3000+)'), (m) {
    return '${m[1]}${'\u3164' * m[2]!.length}';
  });
}
